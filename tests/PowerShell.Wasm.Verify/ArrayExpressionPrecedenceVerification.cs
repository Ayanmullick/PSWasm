using PSWasm;

internal static class ArrayExpressionPrecedenceVerification
{
    public static async ValueTask VerifyAsync()
    {
        // Native PowerShell supplied these expectations. Comma arrays are binary operands, not outer expression lists.
        // https://github.com/PowerShell/PowerShell/blob/411d5fee10110d9881a909804f9d4eb1a06052ea/src/System.Management.Automation/engine/parser/Parser.cs#L6798-L7009
        var cases = new (string Name, string Script, string[] Expected)[]
        {
            ("like_collection",
                "('cat','cot','bat' -like 'c[ao]t') -join ','",
                ["cat,cot"]),
            ("notlike_collection",
                "('cat','cot','bat' -notlike 'c[ao]t') -join ','",
                ["bat"]),
            ("clike_collection",
                "('A','a','b' -clike '[a]') -join ','",
                ["a"]),
            ("add_scalar",
                "(1,2 + 3) -join ','",
                ["1,2,3"]),
            ("add_arrays",
                "(1,2 + 3,4) -join ','",
                ["1,2,3,4"]),
            ("repeat_array",
                "(1,2 * 3) -join ','",
                ["1,2,1,2,1,2"]),
            ("nested_arithmetic",
                "(1,2 + 3,4 * 2) -join ','",
                ["1,2,3,4,3,4"]),
            ("explicit_grouping",
                "(1,(2+3)) -join ','",
                ["1,5"]),
            ("equality",
                "(1,2,3 -eq 2) -join ','",
                ["2"]),
            ("inequality",
                "(1,2,3 -ne 2) -join ','",
                ["1,3"]),
            ("ordering",
                "(1,2,3 -gt 1) -join ','",
                ["2,3"]),
            ("contains",
                "1,2,3 -contains 2",
                ["True"]),
            ("in_rhs",
                "2 -in 1,2,3",
                ["True"]),
            ("logical_and",
                "$false,$false -and $true",
                ["True"]),
            ("logical_or",
                "$false,$false -or $false",
                ["True"]),
            ("logical_xor",
                "$false,$false -xor $true",
                ["False"]),
            ("coalesce_left",
                "(1,2 ?? 3) -join ','",
                ["1,2"]),
            ("coalesce_rhs",
                "($null ?? 1,2) -join ','",
                ["1,2"]),
            ("join_left",
                "'a','b' -join '-'",
                ["a-b"]),
            ("unary_join",
                "(-join 'a','b') -join '-'",
                ["a-b"]),
            ("split_left",
                "('a:b','c:d' -split ':') -join ','",
                ["a,b,c,d"]),
            ("replace_left",
                "('cat','bat' -replace 'a','o') -join ','",
                ["cot,bot"]),
            ("format_rhs",
                "'{0}/{1}' -f 'a','b'",
                ["a/b"]),
            ("range_right_array",
                "try { 1..2,3 } catch { 'rejected' }",
                ["rejected"]),
            ("range_left_array",
                "try { 1,2..3 } catch { 'rejected' }",
                ["rejected"]),
            ("parenthesized_range",
                "((1..2),3).Count; ((1..2),3)[0].Count",
                ["2", "2"]),
            ("unary_comma_nesting",
                "$x=,1,2; $x.Count; $x[0].Count; $x[0][0]; $x[1]",
                ["2", "1", "1", "2"]),
            ("unary_comma_rhs",
                "$x=1,2 + ,3; $x.Count; $x -join ','",
                ["3", "1,2,3"]),
            ("double_unary_comma",
                "$x=,,1,2; $x.Count; $x[0].Count; $x[0][0].Count",
                ["2", "1", "1"]),
            ("cast_element",
                "[int]'1','2' | ForEach-Object { $_.GetType().Name }",
                ["Int32", "String"]),
            ("cast_group",
                "[int[]]('1','2') | ForEach-Object { $_.GetType().Name }",
                ["Int32", "Int32"]),
            ("typed_parallel_assignment",
                "[int]$a,[string]$b=1.2,3 + 4; \"$a|$b|$($a.GetType().Name)|$($b.GetType().Name)\"",
                ["1|3 4|Int32|String"]),
            ("argument_array",
                "function Array-Args { param($x,$y); $x.Count; $x -join ','; $y }; Array-Args 1,2 tail",
                ["2", "1,2", "tail"]),
            ("argument_arithmetic_text",
                "function Array-Args { param($x,$y); $x.Count; $x -join ','; $y }; Array-Args 1,2+3 tail",
                ["2", "1,2+3", "tail"]),
            ("method_arguments",
                "'abcd'.Substring(1,2)",
                ["bc"]),
            ("method_arithmetic_arguments",
                "'abcd'.Substring(0+1,1+1)",
                ["bc"]),
            ("method_nested_array",
                "[Convert]::ToBase64String((65,66 + 67))",
                ["QUJD"]),
            ("method_nested_typed_array",
                "[Convert]::ToBase64String([byte[]](65,66 + 67))",
                ["QUJD"]),
            ("method_ternary_arguments",
                "'abcd'.Substring($true ? 1 : 0, $false ? 1 : 2)",
                ["bc"]),
            ("parameter_nested_default",
                "function Array-Default($x=(1,2+3),$y=4) { $x -join ','; $y }; Array-Default",
                ["1,2,3", "4"]),
            ("index_array",
                "$x=@(10,20,30); ($x[0,1] + 40) -join ','",
                ["10,20,40"]),
            ("index_comparison",
                "$x=@(10,20,30); ($x[0,1 -eq 1]) -join ','",
                ["20"]),
            ("ternary_true_array",
                "($true ? 1,2 + 3 : 4,5) -join ','",
                ["1,2,3"]),
            ("ternary_false_array",
                "($false ? 1,2 : 3,4 + 5) -join ','",
                ["3,4,5"]),
            ("assignment_array",
                "$x = 1,2 + 3; $x -join ','",
                ["1,2,3"]),
            ("short_circuit_array",
                "$x=0; $true -or ($x=1),($x=2); $x",
                ["True", "0"]),
        };
        var failures = new List<string>();
        foreach (var (name, script, expected) in cases)
        {
            try
            {
                var result = await new PowerShellWasmRuntime().ExecuteAsync(script);
                var records = expected.Select(static text => new PowerShellWasmOutputRecord("Output", text));
                if (!result.Records.SequenceEqual(records))
                    failures.Add($"{name}: expected {string.Join(" | ", expected)}; actual {result.Text}");
            }
            catch (Exception exception) { failures.Add($"{name}: {exception.GetType().Name}: {exception.Message}"); }
        }
        Console.WriteLine($"Array expression precedence scenarios: {cases.Length - failures.Count}/{cases.Length} passed.");
        if (failures.Count != 0) throw new InvalidOperationException(string.Join(Environment.NewLine, failures));
    }
}

