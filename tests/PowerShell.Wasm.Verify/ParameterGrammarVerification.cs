                var result = await new PowerShellWasmRuntime().ExecuteAsync(script);
                var records = expected.Select(static text => new PowerShellWasmOutputRecord("Output", text));
                if (!result.Records.SequenceEqual(records))
                    failures.Add($"{name}: expected {string.Join(" | ", expected)}; actual {result.Text}");
            }
            catch (Exception exception) { failures.Add($"{name}: {exception.GetType().Name}: {exception.Message}"); }
        }
        var outputFailures = failures.Count;
        Console.WriteLine($"Parameter grammar output scenarios: {cases.Length - outputFailures}/{cases.Length} passed.");
        foreach (var (name, script) in diagnostics)
        {
            try
            {
                _ = new PowerShellWasmParser().Parse(script);
                failures.Add($"{name}: expected parse rejection, but parsing succeeded.");
            }
            catch (InvalidOperationException) { }
            catch (Exception exception) { failures.Add($"{name}: unexpected {exception.GetType().Name}: {exception.Message}"); }
        }
        Console.WriteLine($"Parameter grammar diagnostics: {diagnostics.Length - (failures.Count - outputFailures)}/{diagnostics.Length} passed.");
        await VerifyParseBeforeExecutionAsync();
        if (failures.Count != 0) throw new InvalidOperationException(string.Join(Environment.NewLine, failures));
    }

    private static async ValueTask VerifyParseBeforeExecutionAsync()
    {
        var runtime = new PowerShellWasmRuntime();
        await runtime.ExecuteAsync("$GrammarSentinel = 'unchanged'");
        var rejected = false;
        try
        {
            await runtime.ExecuteAsync("$GrammarSentinel = 'changed'; function Grammar-Invalid($a,$A) {}; 'not-run'");
        }
        catch (InvalidOperationException) { rejected = true; }
        var result = await runtime.ExecuteAsync("$GrammarSentinel");
        if (!rejected || !result.Records.SequenceEqual([new PowerShellWasmOutputRecord("Output", "unchanged")]))
            throw new InvalidOperationException("Invalid parameter declarations must reject the entire script before any statement executes.");
        Console.WriteLine("Parameter grammar parse-before-execution: passed.");
    }

    private static void VerifyAstCompatibility()
    {
        var legacy = new ParameterDeclarationAst("Value", "int", null, [], []);
        var (name, type, value, aliases, validateSet) = legacy;
        if (name != "Value" || type != "int" || value is not null || aliases.Count != 0 || validateSet.Count != 0 ||
            legacy.AdditionalTypeNames.Count != 0)
            throw new InvalidOperationException("Existing five-position parameter AST construction and deconstruction must remain compatible.");
        var parsed = new PowerShellWasmParser().Parse("param([string][Alias('n')][int]$Value)").Parameters.Single();
        if (parsed.TypeName != "string" || !parsed.AdditionalTypeNames.SequenceEqual(["int"]) ||
            !parsed.Aliases.SequenceEqual(["n"]))
            throw new InvalidOperationException("Parameter AST must retain ordered type constraints independently of attribute placement.");
        var rewritten = parsed with { TypeName = "double" };
        if (rewritten.TypeName != "double" || !rewritten.AdditionalTypeNames.SequenceEqual(["int"]))
            throw new InvalidOperationException("Changing primary TypeName must preserve the additional parameter constraints.");
        Console.WriteLine("Parameter grammar AST compatibility: passed.");
    }
